CREATE TABLE navigation_menus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 150),
  slug TEXT NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 100),
  placement TEXT NOT NULL CHECK (placement IN ('HEADER','FOOTER','SIDEBAR','MOBILE','CUSTOM')),
  status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  current_published_revision_id BIGINT NULL,
  version INTEGER NOT NULL DEFAULT 1,           -- draft version; drives ETag / If-Match
  created_by BIGINT NOT NULL,
  updated_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ
);

-- Slug is unique per website + placement among live (non-archived) menus.
CREATE UNIQUE INDEX uq_nav_menu_slug
  ON navigation_menus (tenant_id, organization_id, website_id, placement, slug)
  WHERE deleted_at IS NULL;
CREATE INDEX idx_nav_menu_scope
  ON navigation_menus (tenant_id, organization_id, website_id, status);
CREATE INDEX idx_nav_menu_public
  ON navigation_menus (website_id, placement)
  WHERE current_published_revision_id IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE navigation_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id BIGINT NOT NULL REFERENCES navigation_menus(id),
  parent_item_id BIGINT NULL,
  label TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 120),
  item_kind TEXT NOT NULL CHECK (item_kind IN ('LINK','GROUP')),
  link_type TEXT NULL CHECK (link_type IN ('INTERNAL_PAGE','EXTERNAL_URL','ANCHOR','APPROVED_SYSTEM_ROUTE')),
  target_page_id BIGINT NULL,                   -- cross-service reference: no FK
  external_url TEXT NULL,
  anchor TEXT NULL,
  system_route TEXT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  open_in_new_tab BOOLEAN NOT NULL DEFAULT false,
  accessibility_label TEXT NULL CHECK (length(accessibility_label) <= 200),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, menu_id),
  -- a parent must live in the same menu (composite FK) and cannot be the item itself
  FOREIGN KEY (parent_item_id, menu_id) REFERENCES navigation_items (id, menu_id) ON DELETE CASCADE,
  CHECK (parent_item_id IS NULL OR parent_item_id <> id),
  CHECK (
    (item_kind = 'GROUP' AND link_type IS NULL AND target_page_id IS NULL
       AND external_url IS NULL AND anchor IS NULL AND system_route IS NULL)
    OR (item_kind = 'LINK' AND (
         (link_type = 'INTERNAL_PAGE' AND target_page_id IS NOT NULL AND external_url IS NULL AND anchor IS NULL AND system_route IS NULL)
      OR (link_type = 'EXTERNAL_URL' AND external_url IS NOT NULL AND target_page_id IS NULL AND anchor IS NULL AND system_route IS NULL)
      OR (link_type = 'ANCHOR' AND anchor IS NOT NULL AND target_page_id IS NULL AND external_url IS NULL AND system_route IS NULL)
      OR (link_type = 'APPROVED_SYSTEM_ROUTE' AND system_route IS NOT NULL AND target_page_id IS NULL AND external_url IS NULL AND anchor IS NULL)
    ))
  )
);
CREATE INDEX idx_nav_items_menu_parent_order
  ON navigation_items (menu_id, parent_item_id, sort_order, id);

CREATE TABLE navigation_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id BIGINT NOT NULL REFERENCES navigation_menus(id),
  revision_number INTEGER NOT NULL CHECK (revision_number > 0),
  document_json JSONB NOT NULL,
  checksum TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ,
  UNIQUE (menu_id, revision_number)
);
-- at most one live published revision per menu
CREATE UNIQUE INDEX uq_nav_revision_published ON navigation_revisions (menu_id) WHERE status = 'PUBLISHED';

-- publication pointer integrity
ALTER TABLE navigation_menus
  ADD CONSTRAINT fk_nav_menu_published_revision
  FOREIGN KEY (current_published_revision_id) REFERENCES navigation_revisions(id);

CREATE TABLE navigation_item_translations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES navigation_items(id) ON DELETE CASCADE,
  locale TEXT NOT NULL,
  label TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 120),
  accessibility_label TEXT NULL CHECK (length(accessibility_label) <= 200),
  UNIQUE (item_id, locale)
);

CREATE TABLE navigation_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL,
  actor_user_id BIGINT NOT NULL,
  action TEXT NOT NULL,
  resource_type TEXT NOT NULL,
  resource_id BIGINT NOT NULL,
  request_id TEXT NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_nav_audit_scope ON navigation_audit_logs (tenant_id, organization_id, website_id, created_at);

CREATE TABLE outbox_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL DEFAULT gen_random_uuid(),
  event_type TEXT NOT NULL,
  payload JSONB NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_outbox_pending ON outbox_events (next_attempt_at) WHERE published_at IS NULL;

CREATE TABLE idempotency_keys (
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  idem_key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  response_status INTEGER,                      -- NULL while the first request is in flight
  response_body JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, organization_id, user_id, idem_key)
);
